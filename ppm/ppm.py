def InitProject(
    ProjName: str | None = None,
    ProjVer: str | None = None,
    MainFile: str | None = None,
    Yes: bool | None = False,
    Author: str | None = None,
    License: str | None = None,
    CustomLicense: str | None = None,
    Description: str | None = None,
    Silent: bool = False,
):
    YLW = "\033[33m"
    # RED = "\033[31m"
    CYN = "\033[36m"
    RST = "\033[0m"
    if ProjName is None:
        ProjName = Path.cwd().name if Yes else str(input(f"{YLW}Program name: {RST}"))
    if ProjVer is None:
        ProjVer = "0.1.0" if Yes else str(input(f"{YLW}Program version: {RST}"))
    if MainFile is None:
        MainFile = "main.py" if Yes else str(input(f"{YLW}Project main file: {RST}"))
    if Author is None:
        Author = (
            "ppm_user" if Yes else str(input(f"{YLW}Author name: {RST}") or "ppm_user")
        )
    if License is None and CustomLicense is None:
        if Yes:
            License = "GPL-3.0-only"
        else:
            user_input = str(
                input(f"{YLW}License (Valid SPDX Licenses, or type 'custom'): {RST}")
                or "GPL-3.0-only"
            )
            if user_input.lower() == "custom":
                CustomLicense = str(
                    input(f"{CYN}Enter Custom License Name: {RST}")
                    or f"{Author}Private"
                )
            else:
                License = user_input

    elif CustomLicense == "" or (License is None and CustomLicense is True):
        CustomLicense = (
            f"{Author}Private"
            if Yes
            else str(input(f"{CYN}Custom License Name: {RST}") or f"{Author}Private")
        )

    if Description is None:
        Description = "" if Yes else str(input(f"{YLW}Short description: {RST}"))

    if not Silent:
        print(f"{YLW}Initializing project{RST} {CYN}{ProjName}: {ProjVer}!{RST}")
    build_base(color=True, shush=True)
    LoadEnv()
    BaseScripts = {
        "ppy": f"{environ['PPM_PYTHON']}",
        "ppip": f"{environ['PPM_PIP']}",
        "project-py": f"{environ['PPM_PYTHON']}",
        "project-pip": f"{environ['PPM_PIP']}",
    }
    TOML = ProjectTOMLHandler(ProjName)
    TOML.SetMeta(ProjVer, MainFile)
    TOML.SetScripts(BaseScripts)
    TOML.BuildTOML(DontWriteDoNotEdit=True)

    PyProjectConfig = {
        "name": ProjName,
        "version": ProjVer,
        "description": Description,
        "requires_python": ">=3.10",
        "license": License,
        "CustomLicense": CustomLicense,
        "author_name": Author,
        "dependencies": {},
        "scripts": {},
    }
    GenFullPyProject(PyProjectConfig)
    if not Silent:
        print(f"{YLW}Generated pyproject.toml!{RST}")

    MainFilePath = Path(MainFile)
    if not MainFilePath.exists():
        MainFilePath.parent.mkdir(parents=True, exist_ok=True)
        MainFilePath.write_text('print("Hello, world!")\n', encoding="utf-8")
        if not Silent:
            print(f"{YLW}Created main file: {MainFile}{RST}")

    DEFAULT_JSON_PYRIGHT = {"venvPath": ".venv", "venv": ".venv"}
    if Path(".ppm_paths").exists():
        LoadEnv()
        CONFIG_JSON = f"{environ['PPM_DIR']}/pyrightconfig.json"
        with open(CONFIG_JSON, "w", encoding="utf-8") as f:
            json.dump(DEFAULT_JSON_PYRIGHT, f, indent=4)
        try:
            with open(CONFIG_JSON, "r", encoding="utf-8") as f:
                existing_data = json.load(f)
        except (FileNotFoundError, json.JSONDecodeError):
            existing_data = {}

        existing_data |= DEFAULT_JSON_PYRIGHT
        with open(CONFIG_JSON, "w", encoding="utf-8") as f:
            json.dump(existing_data, f, indent=4)

    ExpandedPath = Path(__file__).resolve().parent
    ExpandedPathFile = Path(__file__).resolve()
    PPMScriptDir = ExpandedPath / "Scripts" / "ppm"

    PPMScript = PPMScriptDir / ("ppm.bat" if platform == "win32" else "ppm.sh")
    with open(PPMScript, "r", encoding="utf-8") as f:
        content = f.read()
        UpdatedCnt = content.replace("REPLACE_WITH_PATH", str(ExpandedPathFile))
        FileName = "ppm.bat" if platform == "win32" else "ppm.sh"

        with open(f"{environ['PPM_DIR']}/{FileName}", "w") as file:
            file.write(UpdatedCnt)

        if platform != "win32":
            FullFileName = str(Path(f"{environ['PPM_DIR']}/ppm.sh").resolve())
            FileStats = stat(FileName).st_mode
            ExecModeStats = FileStats | S_IXUSR | S_IXGRP | S_IXOTH
            chmod(FullFileName, ExecModeStats)

    # Check if user has git in PATH and init the project dir if there is.
    if which("git") and not Path(f"{environ['PPM_DIR']}/.git").exists():
        run(f"git init {environ['PPM_DIR']}", capture_output=True)

    if not Silent:
        print(f"{CYN}Initialized project!{RST}")


def DeInitProject() -> None | bool:
    # YLW = "\033[33m" # Uncomment this when needed.
    # RED = "\033[31m" # Uncomment this when needed.
    CYN = "\033[36m"
    RST = "\033[0m"
    main_file = _GetMainFileFromTOML()

    delete_base(color=True, delete_ppm_paths=True)
    Path(".gitignore").unlink() if Path(".gitignore").exists() else ""
    Path("ppm.lock").unlink() if Path("ppm.lock").exists() else ""
    Path("ppm.toml").unlink() if Path("ppm.toml").exists() else ""
    Path("pyrightconfig.json").unlink() if Path("pyrightconfig.json").exists() else ""
    Path("pyproject.toml").unlink() if Path("pyproject.toml").exists() else ""
    rmtree(".git") if Path(".git").exists() else ""
    Path(main_file).unlink() if main_file and Path(main_file).exists() else ""

    print(f"{CYN}Deinitialized project!{RST}")
    return True


def _GetMainFileFromTOML() -> Optional[str]:
    """Reads the main_file entry back out of ppm.toml, if it exists."""
    TomlPath = Path("ppm.toml")
    if not TomlPath.is_file():
        return None
    try:
        with TomlPath.open("rb") as f:
            data = tomllib.load(f)
    except Exception:
        return None
    for entries in data.values():
        if isinstance(entries, list):
            for entry in entries:
                if "main_file" in entry:
                    return entry["main_file"]
    return None


def _GetBeShushedOnScriptExecFromTOML() -> bool:
    """Checks if shush_on_script_run is true in [[project_name]]"""
    TomlPath = Path("ppm.toml")
    if not TomlPath.is_file():
        return False
    try:
        with TomlPath.open("rb") as f:
            data = tomllib.load(f)
    except Exception:
        return False
    for entries in data.values():
        if isinstance(entries, list):
            for entry in entries:
                if entry.get("shush_on_script_run", "") == "true":
                    return True
    return False


def _GetScriptsFromTOML() -> dict:
    """Reads the [scripts] table out of ppm.toml, if present."""
    TomlPath = Path("ppm.toml")
    if not TomlPath.is_file():
        return {}
    try:
        with TomlPath.open("rb") as f:
            data = tomllib.load(f)
    except Exception:
        return {}
    scripts = data.get("scripts", {})
    return scripts if isinstance(scripts, dict) else {}


def RunProject(
    MainFile: str, use_global: bool = False, extra_args: list | None = None
) -> bool:
    """Runs the project using either the local venv python or the system-global python."""
    if use_global:
        PythonPath = executable
    else:
        if Path(".ppm_paths").exists():
            LoadEnv()
        BinDir = "Scripts" if platform == "win32" else "bin"
        PythonPath = environ.get("PPM_PYTHON", f".venv/{BinDir}/python{EXE}")
    Cmd = [PythonPath, MainFile] + (extra_args or [])
    Run = run(Cmd)
    return Run.returncode == 0


def RunScriptCommand(ScriptName: str, ScriptArgs: list) -> bool:
    """Runs a named command from ppm.toml's [scripts] table, using a shell
    so scripts can be arbitrary commands (not just python invocations)."""
    scripts = _GetScriptsFromTOML()
    be_shushed_on_script_run = _GetBeShushedOnScriptExecFromTOML()
    if ScriptName not in scripts:
        available = ", ".join(scripts) if scripts else "(none defined)"
        print(
            f"\033[31mNo script named '{ScriptName}' in ppm.toml. Available: {available}\033[0m"
        )
        return False

    LoadEnv()
    BinDir = "Scripts" if platform == "win32" else "bin"
    VenvBin = Path(
        environ.get("PPM_PYTHON", f".venv/{BinDir}/python{EXE}")
    ).parent.resolve()
    Env = environ.copy()
    if VenvBin.is_dir():
        Env["PATH"] = f"{VenvBin}{pathsep}{Env.get('PATH', '')}"

    if not be_shushed_on_script_run:
        print(f"\033[33m> {scripts[ScriptName]}\033[0m")

    Result = run([scripts[ScriptName], *ScriptArgs], shell=True, env=Env)
    return Result.returncode == 0


