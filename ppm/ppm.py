def _GetArgValue(Args: list, Flag: str) -> Optional[str]:
    """Helper to fetch the value following a flag in the CLI args, if present."""
    if Flag in Args:
        Idx = Args.index(Flag) + 1
        if Idx < len(Args):
            return Args[Idx]
    return None


def _GetPositionalArgs(Args: list, flags_with_values: set) -> list:
    """Returns Args (excluding Args[0], the command itself) with all --flags
    and the values they consume stripped out, leaving only true positionals.
    Prevents a flag's value (e.g. 'dev' in --branch dev) from being
    mistaken for a positional argument."""
    Positional = []
    skip_next = False
    for a in Args[1:]:
        if skip_next:
            skip_next = False
            continue
        if a.startswith("--"):
            if a in flags_with_values:
                skip_next = True
            continue
        Positional.append(a)
    return Positional


def _CLI():
    if len(argv) < 2:
        print(
            f"{RED}No arguments supplied! Use 'help' or 'h' or '--help' or '-h' for usage.{RST}"
        )
